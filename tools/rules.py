def first(pattern, default=None, group=1):
    def f(text):
        m = re.search(pattern, text)
        return m.group(group).strip() if m else default
    return f


def surah(text):
    m = re.search(r"سور" + H + r"\s+(" + A + r"?ل?[ء-ي]+)", text)
    return "سورة " + m.group(1) if m else None


def ghazwa(text):
    m = re.search(r"(غزو" + H + r"\s+[ء-ي]+(?:\s+[ء-ي]+)?)", text)
    if m:
        g = m.group(1).replace("غزوه", "غزوة")
        g = re.sub(r"\s+(تأملات|وقفات|و|من|في|-).*$", "", g)
        if "المريسيع" in g or "المصطلق" in g:
            return "غزوة بني المصطلق (المريسيع)"
        return g
    for k, v in [("الإفك", "حادثة الإفك"), ("الافك", "حادثة الإفك"), ("احد", "غزوة أحد"),
                 ("أحد", "غزوة أحد"), ("مكاتب", "مكاتبة الملوك والأمراء"),
                 ("الوفود", "عام الوفود"), ("حج" + H + " الوداع", "حجة الوداع"),
                 ("الحيا" + H + " الطيب", "آخر باب من الحياة الطيبة"), ("حصاد", "حصاد سنوات الدعوة")]:
        if re.search(k, text):
            return v
    return "لقاءات متفرقة"


def prophet(text):
    if "مؤمن آل فرعون" in text:
        return "مؤمن آل فرعون"
    m = re.search(r"نب" + Y + r" الله\s+([ء-ي]+(?:\s+بن\s+[ء-ي]+)?)", text)
    return m.group(1) if m else None


def manar(text):
    for k, v in [("الصلا", "الصلاة"), ("الصيام", "الصيام"), ("الزكا", "الزكاة"),
                 ("الحج", "الحج"), ("الطهار", "الطهارة"), ("الامام|الإمام", "الإمامة")]:
        if re.search(k, text):
            return v
    return None


def name_of_allah(text):
    m = re.search(r"اسم الله\s*\"?\s*([^\"\n]+?)\s*\"", text) or re.search(r"اسم الله\s+([ء-ي،, ]+)", text)
    if not m:
        return None
    name = re.sub(r"[\s\-–]*\d+$", "", m.group(1)).strip(" ،,-–")
    return re.sub(r"\s*،\s*", "، ", name)


def econ(text):
    if re.search(r"فقه الشركات", text):
        return "شرح أصول فقه الشركات"
    if re.search(r"مختصر فقه البيوع", text):
        return "شرح مختصر فقه البيوع"
    if re.search(r"استشار|فتاو|فتو|#حكم|حكم |أسئل|اسئل", text):
        return "استشارات وفتاوى اقتصادية"
    if re.search(r"ندو|نادي|الذكاء الاصطناعي|إثراء|اثراء", text):
        return "ندوات ومحاضرات عامة"
    return "محاضرات في الاقتصاد الإسلامي"


